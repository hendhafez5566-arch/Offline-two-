import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve(import.meta.dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const vendor=read('server/src/vendor.ts');
const ui=read('src/commercial/vendor-owner.ts');
const license=read('server/src/license.ts');
const docker=read('Dockerfile.customer');
assert.match(vendor,/Customer hardened build/);
assert.match(vendor,/reason:'customer_build'/);
assert.doesNotMatch(vendor,/railwayGraphql|vendor_clients|projectCreate/);
assert.match(ui,/enabled:false/);
assert.doesNotMatch(ui,/fetch\(['"]\/api\/vendor/);
assert.match(license,/license-public\.pem/);
assert.match(license,/license-public-central\.pem/);
assert.match(license,/ERP_LICENSE_PUBLIC_KEYS_B64/);
assert.ok(fs.existsSync(path.join(root,'server/license-public.pem')));
assert.ok(fs.existsSync(path.join(root,'server/license-public-central.pem')));
assert.match(docker,/license-public\*\.pem/);
assert.match(docker,/ENV VENDOR_MODE=false/);
console.log('PASS central vendor customer hardening + dual-key licensing');
